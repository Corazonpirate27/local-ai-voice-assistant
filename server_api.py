"""
Groq-Powered FastAPI & WebSocket Server Bridge for Voice Assistant & Root Academy Web UI.
Executes Python tools (play_media, create_homework_docx, web_search, calculate) directly when requested,
or uses Groq / Ollama for general reasoning.
"""

import os
import sys
import json
import urllib.request
from typing import List, Dict, Any, Optional

from fastapi import FastAPI, WebSocket, WebSocketDisconnect, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel

# Add voice-assistant directory to python path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import tools as T
import assistant as A

app = FastAPI(title="Groq-Powered Voice Assistant & Root Academy API Bridge")

# Allow CORS for Root Academy frontend
app.add_middleware(
    CORSMiddleware,
    allow_origins=["*"],
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

GROQ_API_URL = "https://api.groq.com/openai/v1/chat/completions"
GROQ_DEFAULT_MODEL = "llama-3.3-70b-versatile"
GROQ_API_KEY = os.environ.get("VA_GROQ_KEY", os.environ.get("GROQ_API_KEY", ""))


class ChatRequest(BaseModel):
    prompt: str
    api_key: Optional[str] = None
    model: Optional[str] = None
    history: Optional[List[Dict[str, str]]] = None


class ChatResponse(BaseModel):
    reply: str
    model_used: str = GROQ_DEFAULT_MODEL
    tool_results: List[str] = []


@app.get("/api/health")
def health_check():
    return {
        "status": "online",
        "engine": "Groq & Python Tool Agent Engine",
        "default_model": GROQ_DEFAULT_MODEL,
        "speed": "500+ tokens/sec"
    }


@app.post("/api/chat", response_model=ChatResponse)
def chat_endpoint(req: ChatRequest):
    prompt = req.prompt.strip()
    if not prompt:
        raise HTTPException(status_code=400, detail="Empty prompt")

    key = req.api_key or GROQ_API_KEY
    model = req.model or GROQ_DEFAULT_MODEL
    tool_logs = []
    prompt_low = prompt.lower()

    # Direct Python Tool Dispatching
    if "play" in prompt_low or "youtube" in prompt_low or "song" in prompt_low or "music" in prompt_low:
        q = prompt.replace("search youtube and play", "").replace("search youtube", "").replace("play music", "").replace("play", "").replace("on youtube", "").strip()
        query_text = q if q else "lofi study beats"
        res = T.play_media(query_text, "youtube")
        tool_logs.append(res)
        return ChatResponse(
            reply=f"🎵 **Action Executed**: {res}\n\nOpened YouTube in your browser to play **\"{query_text}\"**!",
            model_used="python_play_media_tool",
            tool_results=tool_logs
        )
    elif "homework" in prompt_low or "essay" in prompt_low or "assignment" in prompt_low or "docx" in prompt_low or "document" in prompt_low:
        title = prompt.split("on")[-1].strip() if "on" in prompt else "AI & Cyber Security Assignment"
        res = T.create_homework_docx(
            title.title(),
            f"# {title.title()}\n\nExecutive Summary:\nThis document was generated by your ROOT AGENTIC AI Assistant.\n\n## Core Findings & Analysis\n- Comprehensive research and structured insights.\n- Detailed study breakdown and practical recommendations.\n\n## Conclusion\n- Key conclusions and next steps.",
            "homework_assignment",
            "Documents"
        )
        tool_logs.append(res)
        return ChatResponse(
            reply=f"📄 **Action Executed**: {res}\n\nGenerated and saved your MS Word document to your Documents folder!",
            model_used="python_docx_tool",
            tool_results=tool_logs
        )
    elif ("search" in prompt_low or "find" in prompt_low or "google" in prompt_low) and "youtube" not in prompt_low:
        res = T.web_search(prompt, max_results=3)
        tool_logs.append(str(res))
        return ChatResponse(
            reply=f"🌐 **Web Search Results**:\n\n{res}",
            model_used="python_web_search_tool",
            tool_results=tool_logs
        )
    elif "calculate" in prompt_low or "math" in prompt_low or "solve" in prompt_low:
        calc_expr = prompt.replace("calculate", "").replace("solve", "").replace("math", "").strip()
        res = T.calculate(calc_expr)
        return ChatResponse(
            reply=f"🧮 **Calculation Result**:\n\nExpression: `{calc_expr}`\nResult = **{res}**",
            model_used="python_calculator_tool",
            tool_results=[str(res)]
        )

    # Groq Cloud API Engine
    if key and key.strip().startswith("gsk_"):
        messages = [
            {
                "role": "system",
                "content": "You are ROOT AGENTIC AI, powered by Groq Llama 3.3 70B. Provide clear, concise, direct answers with markdown headings (#, ##), bold points, and code snippets."
            }
        ]

        if req.history:
            for m in req.history:
                if m.get("role") in ("user", "assistant") and m.get("content"):
                    messages.append({"role": m["role"], "content": m["content"]})

        messages.append({"role": "user", "content": prompt})

        headers = {"Content-Type": "application/json", "Authorization": f"Bearer {key.strip()}"}
        payload = json.dumps({
            "model": model,
            "messages": messages,
            "temperature": 0.5,
            "max_tokens": 600
        }).encode("utf-8")

        try:
            http_req = urllib.request.Request(GROQ_API_URL, data=payload, headers=headers)
            with urllib.request.urlopen(http_req) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                reply = data.get("choices", [{}])[0].get("message", {}).get("content", "Groq response received.")
                return ChatResponse(reply=reply, model_used=model, tool_results=tool_logs)
        except Exception:
            pass

    # Local Ollama Agent Fallback (100% free, zero key required)
    try:
        local_model = A.pick_tool_model(A.available_models()) or "qwen3:4b"
        history = req.history or []
        history.append({"role": "user", "content": prompt})

        class DummySpeaker:
            def begin(self, ev=None): pass
            def feed(self, text): pass
            def end(self): pass
            def say_blocking(self, text): pass
            def close(self): pass

        reply = A.agent_respond(history, DummySpeaker(), local_model, lambda act: True)
        return ChatResponse(reply=reply or "Task completed.", model_used=local_model, tool_results=tool_logs)
    except Exception as exc:
        return ChatResponse(reply=f"Agent response: {exc}", model_used="qwen3:4b", tool_results=tool_logs)


if __name__ == "__main__":
    import uvicorn
    print("⚡ Starting Groq & Python Tool API Bridge on http://127.0.0.1:8000...")
    uvicorn.run(app, host="127.0.0.1", port=8000)
